local parse = require('lib.parse')
local ME = parse.ME

local function ev(line) return parse.line(line) or {} end

case("parse: melee hits by the player, on the player, between others, by pets", function()
  local e = ev("You slash a gnoll pup for 12 points of damage.")
  eq(e.kind, "melee") eq(e.src, ME) eq(e.dst, "a gnoll pup") eq(e.amount, 12) eq(e.ability, "slash")
  e = ev("A large rat bites YOU for 1 point of damage.")
  eq(e.src, "A large rat") eq(e.dst, ME) eq(e.amount, 1) eq(e.ability, "bite")
  e = ev("Soandso crushes a decaying skeleton for 31 points of damage.")
  eq(e.src, "Soandso") eq(e.dst, "a decaying skeleton") eq(e.ability, "crush", "third person to base form")
  e = ev("Soandso`s warder claws a gnoll for 8 points of damage.")
  eq(e.src, "Soandso`s warder") eq(e.dst, "a gnoll") eq(e.ability, "claw")
  e = ev("Gobaner frenzies on a gnoll for 40 points of damage.")
  eq(e.src, "Gobaner") eq(e.ability, "frenzy on") eq(e.dst, "a gnoll", "two-word verb")
  e = ev("You hit a fire beetle for 1,204 points of damage.")
  eq(e.amount, 1204, "thousands separators")
  e = ev("Soandso hits a hit squad leader for 5 points of damage.")
  eq(e.src, "Soandso") eq(e.dst, "a hit squad leader", "the first verb splits")
end)

case("parse: misses, blocks and parries", function()
  local e = ev("You try to hit a rat, but miss!")
  eq(e.kind, "miss") eq(e.src, ME) eq(e.dst, "a rat") eq(e.how, "miss")
  e = ev("A rat tries to bite YOU, but YOU parry!")
  eq(e.kind, "miss") eq(e.src, "A rat") eq(e.dst, ME) eq(e.how, "parry")
  e = ev("Soandso tries to frenzy on a gnoll, but a gnoll dodges!")
  eq(e.src, "Soandso") eq(e.dst, "a gnoll") eq(e.ability, "frenzy on")
end)

case("parse: spells, damage shields and damage over time", function()
  local e = ev("Soandso hit a gnoll for 520 points of non-melee damage.")
  eq(e.kind, "spell") eq(e.src, "Soandso") eq(e.dst, "a gnoll") eq(e.amount, 520)
  e = ev("A gnoll was hit by non-melee for 6 points of damage.")
  eq(e.kind, "ds", "434 before the melee shape") eq(e.src, ME) eq(e.dst, "A gnoll") eq(e.amount, 6)
  e = ev("A gnoll has taken 44 damage from your Poison Bolt.")
  eq(e.kind, "dot") eq(e.src, ME) eq(e.dst, "A gnoll") eq(e.ability, "Poison Bolt") eq(e.amount, 44)
  e = ev("A gnoll has taken 30 damage from Soandso by Heat Blood.")
  eq(e.src, "Soandso") eq(e.ability, "Heat Blood")
  e = ev("You have taken 12 damage from A gnoll shaman by Tainted Breath")
  eq(e.kind, "dot") eq(e.dst, ME) eq(e.src, "A gnoll shaman") eq(e.ability, "Tainted Breath")
end)

case("parse: crits and deaths", function()
  local e = ev("Soandso scores a critical hit! (88)")
  eq(e.kind, "crit") eq(e.src, "Soandso") eq(e.amount, 88)
  e = ev("You deliver a critical blast! (1200)")
  eq(e.kind, "crit") eq(e.src, ME)
  e = ev("Soandso lands a Crippling Blow!(150)")
  eq(e.kind, "crit")
  e = ev("You have slain a gnoll!")
  eq(e.kind, "death") eq(e.victim, "a gnoll") eq(e.killer, ME)
  e = ev("A gnoll has been slain by Soandso!")
  eq(e.victim, "A gnoll") eq(e.killer, "Soandso")
  e = ev("A gnoll has been slain by an unseen hand!")
  eq(e.victim, "A gnoll") eq(e.killer, nil)
  e = ev("You have been slain by a gnoll!")
  eq(e.victim, ME) eq(e.killer, "a gnoll")
end)

case("parse: other lines are not events", function()
  eq(parse.line("Soandso tells you, 'I hit a rat for 5 points of damage.'"), nil, "a tell quoting a hit")
  eq(parse.line("You have taken 50 points of damage."), nil, "a spell on you: no attacker")
  eq(parse.line("You begin casting Poison Bolt."), nil)
  eq(parse.line(""), nil)
  eq(parse.line(nil), nil)
  eq(parse.display_name("a_gnoll_pup01"), "a gnoll pup")
end)
