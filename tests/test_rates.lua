local rates = require('lib.rates')

case("rates: coin from loot lines, in platinum per hour", function()
  eq(rates.copper_of("3 platinum, 2 gold, 1 silver and 5 copper"), 3215)
  eq(rates.copper_of("12 platinum"), 12000)
  eq(rates.copper_of("4 gold and 2 copper"), 402)
  local r = rates.new(0, 1000)
  eq(rates.line(r, "You receive 3 platinum and 5 copper from the corpse."), true)
  eq(rates.line(r, "You receive 1 platinum, 5 gold and 2 silver as your split."), true)
  eq(rates.line(r, "You receive 4 platinum from Soandso."), false, "a trade is not loot")
  eq(rates.line(r, "Soandso tells you, 'You receive 9 platinum from the corpse.'"), false)
  eq(r.copper, 4525)
  eq(r.loots, 2)
  eq(rates.summary(r, 30000).plat_hour, nil, "no rate in the first minute")
  local s = rates.summary(r, 1800000) -- half an hour
  eq(s.plat, 4.525)
  eq(s.plat_hour, 9.05)
end)

case("rates: NMSloot sales count as platinum, apart from loot", function()
  local r = rates.new(0, 0)
  eq(rates.line(r, "[NMS] Shield of the Immaculate sold for 9 platinum."), true)
  eq(rates.line(r, "[19:34:02] [NMS] Legionnaire Scale Vambraces (Enchanted) sold for 2 platinum, 3 gold."), true,
    "with a timestamp, and an item name in brackets")
  eq(rates.line(r, "[NMS] Robe sold for nothing."), false)
  eq(rates.line(r, "Soandso says, '[NMS] Robe sold for 9 platinum.'"), false, "only the server's line")
  rates.line(r, "You receive 1 platinum from the corpse.")
  eq(r.sold, 11300) eq(r.sales, 2) eq(r.copper, 1000)
  local s = rates.summary(r, 3600000)
  eq(s.plat, 12.3) eq(s.sold, 11.3) eq(s.looted, 1) eq(s.plat_hour, 12.3)
  rates.reset(r, 0, 0)
  eq(r.sold, 0) eq(r.sales, 0)
end)

case("rates: AA gained from points and progress; spending is no loss", function()
  local r = rates.new(0, 0)
  rates.aa_sample(r, nil, nil)
  rates.aa_sample(r, 5, 40)
  eq(r.aa, 0, "the first sample is the baseline")
  rates.aa_sample(r, 5, 90)
  eq(r.aa, 0.5)
  rates.aa_sample(r, 6, 20) -- a point gained, 20% into the next
  eq(math.floor(r.aa * 100 + 0.5), 80)
  rates.aa_sample(r, 2, 20) -- four spent
  eq(math.floor(r.aa * 100 + 0.5), 80, "spending is not a loss")
  rates.aa_sample(r, 2, 70)
  eq(math.floor(r.aa * 100 + 0.5), 130)
  eq(math.floor(rates.summary(r, 3600000).aa_hour * 100 + 0.5), 130)
  rates.reset(r, 3600000, 5)
  eq(r.aa, 0) eq(r.copper, 0)
  rates.aa_sample(r, 2, 80)
  eq(math.floor(r.aa * 100 + 0.5), 10, "counts on from the last sample after a reset")
end)
